"""Side-by-side comparison of two eval runs (vision vs text-only) -> reports/vision_vs_text.md

    python scripts/compare_modes.py [--a reports/eval_results.json] [--b reports/eval_results_text_only.json]

Every number comes from the two eval JSON files.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from eval import TABLE_ROWS, pct  # noqa: E402

KIND_LABEL = {"pdf_text": "digital PDF", "pdf_scan": "scanned PDF", "image": "photo (JPG)"}


def load(p: Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8"))


def correct_fields(doc: dict) -> tuple[int, int]:
    f = {k: v for k, v in doc["fields"].items() if k in TABLE_ROWS and k != "doc_exact"}
    return sum(v["correct"] for v in f.values()), len(f)


def build(a: dict, b: dict) -> str:
    la, lb = a.get("mode", "vision"), b.get("mode", "text")
    sa, sb = a["summary"], b["summary"]
    out = [f"# Input mode comparison: {la} vs {lb}", "",
           f"Same model (`{a['model']}`), same prompt rules (`{a['prompt_version']}`), same 10 labelled docs. "
           "Only the input changes: page images vs text extracted from the PDF with pdfplumber "
           "(photos and scanned PDFs have no text layer, so their text is empty). "
           "Generated by `scripts/compare_modes.py`.", "",
           "## Field accuracy", "", f"| Field | {la} | {lb} |", "|---|---|---|"]
    for f in TABLE_ROWS:
        ra, rb = sa["fields"][f], sb["fields"][f]
        out.append(f"| {f} | {ra['correct']}/{ra['n']} ({pct(ra['accuracy'])}) | "
                   f"{rb['correct']}/{rb['n']} ({pct(rb['accuracy'])}) |")
    lia, lib = sa["line_items_item_level"], sb["line_items_item_level"]
    out += [f"| line items F1 (item level) | {pct(lia['f1'])} | {pct(lib['f1'])} |",
            f"| non_invoice_nulls | {sa['non_invoice_nulls']['correct']}/{sa['non_invoice_nulls']['n']} | "
            f"{sb['non_invoice_nulls']['correct']}/{sb['non_invoice_nulls']['n']} |", "",
            "## Per document (fields correct / fields scored)", "",
            f"| Doc | Input | {la} | {lb} | {lb}: what came back |", "|---|---|---|---|---|"]
    bdocs = {d["doc"]: d for d in b["docs"]}
    for d in a["docs"]:
        db = bdocs[d["doc"]]
        ca, na = correct_fields(d)
        cb, nb = correct_fields(db)
        p = db["pred"]
        if p.get("error"):
            what = f"error {p['error']['code']}"
        elif p.get("is_invoice") is False:
            what = "is_invoice=false" + (" (wrong)" if d["gt"]["is_invoice"] else "")
        else:
            what = "needs_review: " + "; ".join(r[:50] for r in p.get("review_reasons", [])) \
                if p.get("needs_review") else "ok"
        chars = (db.get("meta") or {}).get("text_chars")
        out.append(f"| {d['doc']} | {KIND_LABEL.get(d['input_kind'], d['input_kind'])}"
                   f"{f' ({chars} chars)' if chars is not None else ''} | {ca}/{na} | {cb}/{nb} | {what} |")

    out += ["", "## By input type (doc exact match)", "", f"| Input type | Docs | {la} | {lb} |", "|---|---|---|---|"]
    for kind in ("pdf_text", "pdf_scan", "image"):
        da = [d for d in a["docs"] if d["input_kind"] == kind and "doc_exact" in d["fields"]]
        if not da:
            continue
        ea = sum(d["fields"]["doc_exact"]["correct"] for d in da)
        eb = sum(bdocs[d["doc"]]["fields"]["doc_exact"]["correct"] for d in da)
        out.append(f"| {KIND_LABEL[kind]} invoices | {len(da)} | {ea}/{len(da)} | {eb}/{len(da)} |")

    ca_, cb_ = sa["cost"], sb["cost"]
    out += ["", "## Cost", "", f"| | {la} | {lb} |", "|---|---|---|",
            f"| tokens in | {ca_['tokens_in']} | {cb_['tokens_in']} |",
            f"| tokens out | {ca_['tokens_out']} | {cb_['tokens_out']} |",
            f"| list-price cost, total | ${ca_['cost_usd']:.4f} | ${cb_['cost_usd']:.4f} |",
            f"| avg / doc | ${ca_['avg_cost_usd']:.5f} | ${cb_['avg_cost_usd']:.5f} |", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    # The text-only run used prompt v1, so compare against the v1 vision run.
    ap.add_argument("--a", default=str(ROOT / "reports" / "eval_results_v1.json"))
    ap.add_argument("--b", default=str(ROOT / "reports" / "eval_results_text_only.json"))
    ap.add_argument("--out", default=str(ROOT / "reports" / "vision_vs_text.md"))
    args = ap.parse_args()
    md = build(load(Path(args.a)), load(Path(args.b)))
    Path(args.out).write_text(md, encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
